# ── PALETTE ───────────────────────────────────────────────────────────────────
BG    = RGBColor(0x0E, 0x0E, 0x0E)
GOLD  = RGBColor(0xE8, 0xA0, 0x20)
WHITE = RGBColor(0xFF, 0xFF, 0xFF)
LGRAY = RGBColor(0xBB, 0xBB, 0xBB)
DGRAY = RGBColor(0x28, 0x28, 0x28)
MGRAY = RGBColor(0x1A, 0x1A, 0x1A)

W = Inches(13.33)
H = Inches(7.5)
IMG_DIR = "/tmp/art_pptx_imgs"

# ── HELPERS ───────────────────────────────────────────────────────────────────
def new_prs():
    p = Presentation()
    p.slide_width  = W
    p.slide_height = H
    return p

def blank(prs):
    return prs.slides.add_slide(prs.slide_layouts[6])

def bg(slide, c=BG):
    fill = slide.background.fill
    fill.solid(); fill.fore_color.rgb = c

def box(slide, x, y, w, h, color):
    s = slide.shapes.add_shape(1, x, y, w, h)
    s.fill.solid(); s.fill.fore_color.rgb = color
    s.line.fill.background()
    return s

def txt(slide, text, x, y, w, h,
        size=14, bold=False, italic=False,
        color=WHITE, align=PP_ALIGN.LEFT, wrap=True):
    if not text: return
    tb = slide.shapes.add_textbox(x, y, w, h)
    tf = tb.text_frame; tf.word_wrap = wrap
    # handle multi-paragraph (split on \n)
    lines = str(text).split('\n')
    for i, line in enumerate(lines):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = align
        r = p.add_run(); r.text = line
        r.font.size = Pt(size); r.font.bold = bold
        r.font.italic = italic; r.font.color.rgb = color

def img_fit(slide, name, bx, by, bw, bh, bg_color=MGRAY):
    """
    Place image preserving aspect ratio, centered in bounding box.
    Draws a dark background rect first so empty space looks intentional.
    Returns True if image placed.
    """
    path = os.path.join(IMG_DIR, name)
    if not os.path.exists(path) or os.path.getsize(path) < 5000:
        return False
    try:
        pil = PILImage.open(path)
        iw, ih = pil.size
        scale = min(bw / iw, bh / ih)
        fw = int(iw * scale)
        fh = int(ih * scale)
        fx = bx + (bw - fw) // 2
        fy = by + (bh - fh) // 2
        # dark background
        box(slide, bx, by, bw, bh, bg_color)
        slide.shapes.add_picture(path, fx, fy, fw, fh)
        return True
    except Exception as e:
        print(f"  ⚠ {name}: {e}")
        return False

def img_row(slide, names, y, h, margin_x=Inches(6.3), total_w=None):
    """Place a row of images with equal spacing, each preserving ratio."""
    total_w = total_w or (W - margin_x - Inches(0.15))
    names = [n for n in names if os.path.exists(os.path.join(IMG_DIR, n))
             and os.path.getsize(os.path.join(IMG_DIR, n)) > 5000]
    if not names: return
    n = len(names)
    gap = Inches(0.08)
    each_w = (total_w - gap * (n - 1)) / n
    for i, name in enumerate(names):
        x = margin_x + i * (each_w + gap)
        img_fit(slide, name, x, y, each_w, h)

def img_grid(slide, names, y_start, total_h, margin_x=Inches(6.3), total_w=None):
    """2x2 grid layout."""
    total_w = total_w or (W - margin_x - Inches(0.15))
    names = [n for n in names if os.path.exists(os.path.join(IMG_DIR, n))
             and os.path.getsize(os.path.join(IMG_DIR, n)) > 5000]
    if not names: return
    n = len(names)
    if n <= 2:
        img_row(slide, names, y_start, total_h, margin_x, total_w)
        return
    gap = Inches(0.08)
    col_w = (total_w - gap) / 2
    row_h = (total_h - gap) / 2
    positions = [
        (margin_x,           y_start),
        (margin_x + col_w + gap, y_start),
        (margin_x,           y_start + row_h + gap),
        (margin_x + col_w + gap, y_start + row_h + gap),
    ]
    for i, name in enumerate(names[:4]):
        img_fit(slide, name, positions[i][0], positions[i][1], col_w, row_h)

# ── SLIDE TYPES ───────────────────────────────────────────────────────────────
def title_slide(prs, line1, line2=""):
    s = blank(prs); bg(s)
    box(s, 0, 0, W, Inches(.08), GOLD)
    box(s, 0, H - Inches(.08), W, Inches(.08), GOLD)
    box(s, Inches(.6), Inches(2.6), Inches(12.13), Inches(2.6), DGRAY)
    txt(s, line1, Inches(.8), Inches(2.75), Inches(11.73), Inches(1.7),
        size=34, bold=True, color=GOLD, align=PP_ALIGN.CENTER)
    if line2:
        txt(s, line2, Inches(.8), Inches(4.6), Inches(11.73), Inches(.55),
            size=17, color=LGRAY, align=PP_ALIGN.CENTER)

def section_slide(prs, title):
    s = blank(prs); bg(s)
    box(s, 0, 0, W, Inches(.08), GOLD)
    box(s, 0, H - Inches(.08), W, Inches(.08), GOLD)
    box(s, 0, Inches(3.0), W, Inches(1.5), DGRAY)
    txt(s, title, Inches(.5), Inches(3.05), Inches(12.33), Inches(1.4),
        size=32, bold=True, color=GOLD, align=PP_ALIGN.CENTER)

def q_slide(prs, num, question, answer_lines, image_names=None):
    """
    image_names: list of filenames. Auto-selects layout:
      1 image  → right half
      2 images → right half split vertically
      3 images → right side in row
      4 images → 2×2 grid on right
      None/[]  → full-width text
    """
    s = blank(prs); bg(s)
    box(s, 0, 0, W, Inches(.06), GOLD)

    # Number badge
    box(s, Inches(.12), Inches(.1), Inches(.62), Inches(.52), GOLD)
    txt(s, str(num), Inches(.12), Inches(.09), Inches(.62), Inches(.53),
        size=20, bold=True, color=BG, align=PP_ALIGN.CENTER)

    # Question
    txt(s, question, Inches(.87), Inches(.1), Inches(11.3), Inches(.55),
        size=12.5, bold=True, color=GOLD)

    # Divider
    box(s, Inches(.12), Inches(.73), Inches(13.0), Inches(.024), DGRAY)

    # Decide layout
    avail = [n for n in (image_names or [])
             if os.path.exists(os.path.join(IMG_DIR, n))
             and os.path.getsize(os.path.join(IMG_DIR, n)) > 5000]

    if avail:
        text_w = Inches(5.85)
        img_x  = Inches(6.1)
        img_w  = W - img_x - Inches(.12)
        img_y  = Inches(.8)
        img_h  = H - img_y - Inches(.1)
    else:
        text_w = Inches(12.85)

    # Render text
    full = '\n'.join(answer_lines)
    txt(s, full, Inches(.18), Inches(.82), text_w, Inches(6.35),
        size=12.5, color=WHITE, wrap=True)

    # Render images
    if avail:
        if len(avail) == 1:
            img_fit(s, avail[0], img_x, img_y, img_w, img_h)
        elif len(avail) == 2:
            img_row(s, avail, img_y, img_h, img_x, img_w)
        elif len(avail) == 3:
            img_row(s, avail, img_y, img_h, img_x, img_w)
        else:
            img_grid(s, avail, img_y, img_h, img_x, img_w)

