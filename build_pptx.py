from pptx.util import Inches, Pt
from pptx.dml.color import RGBColor
from pptx.enum.text import PP_ALIGN

# ── PALETTE ───────────────────────────────────────────────────────────────────
BG    = RGBColor(0x0E, 0x0E, 0x0E)
GOLD  = RGBColor(0xE8, 0xA0, 0x20)
WHITE = RGBColor(0xFF, 0xFF, 0xFF)
LGRAY = RGBColor(0xBB, 0xBB, 0xBB)
DGRAY = RGBColor(0x28, 0x28, 0x28)
GREEN = RGBColor(0x5A, 0xB8, 0x5C)
RED   = RGBColor(0xD0, 0x4A, 0x4A)

W = Inches(13.33)
H = Inches(7.5)
IMG_DIR = "/tmp/art_pptx_imgs"

# ── LOW-LEVEL HELPERS ─────────────────────────────────────────────────────────
def prs_new():
    p = Presentation()
    p.slide_width  = W
    p.slide_height = H
    return p

def slide_blank(prs):
    return prs.slides.add_slide(prs.slide_layouts[6])

def bg(slide, c=BG):
    fill = slide.background.fill
    fill.solid()
    fill.fore_color.rgb = c

def rect(slide, x, y, w, h, color, line=False):
    s = slide.shapes.add_shape(1, x, y, w, h)
    s.fill.solid(); s.fill.fore_color.rgb = color
    if line: s.line.color.rgb = color
    else: s.line.fill.background()
    return s

def txt(slide, text, x, y, w, h,
        size=14, bold=False, italic=False,
        color=WHITE, align=PP_ALIGN.LEFT, wrap=True):
    tb = slide.shapes.add_textbox(x, y, w, h)
    tf = tb.text_frame; tf.word_wrap = wrap
    p = tf.paragraphs[0]; p.alignment = align
    r = p.add_run(); r.text = text
    r.font.size = Pt(size); r.font.bold = bold
    r.font.italic = italic; r.font.color.rgb = color
    return tb

def img(slide, name, x, y, w, h):
    path = os.path.join(IMG_DIR, name)
    if os.path.exists(path) and os.path.getsize(path) > 3000:
        try:
            slide.shapes.add_picture(path, x, y, w, h)
            return True
        except: pass
    return False

# ── SLIDE TEMPLATES ───────────────────────────────────────────────────────────
def title_slide(prs, t1, t2=""):
    s = slide_blank(prs); bg(s)
    rect(s, 0, 0, W, Inches(.07), GOLD)
    rect(s, 0, H-Inches(.07), W, Inches(.07), GOLD)
    rect(s, Inches(.6), Inches(2.8), Inches(12.1), Inches(2.5), DGRAY)
    txt(s, t1, Inches(.8), Inches(2.9), Inches(11.7), Inches(1.5),
        size=36, bold=True, color=GOLD, align=PP_ALIGN.CENTER)
    if t2:
        txt(s, t2, Inches(.8), Inches(4.5), Inches(11.7), Inches(.6),
            size=18, color=LGRAY, align=PP_ALIGN.CENTER)

def section_slide(prs, title):
    s = slide_blank(prs); bg(s)
    rect(s, 0, 0, W, Inches(.07), GOLD)
    rect(s, 0, H-Inches(.07), W, Inches(.07), GOLD)
    rect(s, 0, Inches(2.9), W, Inches(1.7), DGRAY)
    txt(s, title, Inches(.5), Inches(3.0), Inches(12.3), Inches(1.5),
        size=34, bold=True, color=GOLD, align=PP_ALIGN.CENTER)

def q_slide(prs, num, question, answers, images=None):
    """
    answers: list of (symbol, text) tuples  e.g. [('✅','correct'), ('❌','wrong')]
             OR plain strings
    images: list of (filename, caption) OR just filenames
    """
    s = slide_blank(prs); bg(s)
    # top bar
    rect(s, 0, 0, W, Inches(.055), GOLD)
    # number badge
    rect(s, Inches(.12), Inches(.1), Inches(.6), Inches(.5), GOLD)
    txt(s, str(num), Inches(.12), Inches(.08), Inches(.6), Inches(.52),
        size=18, bold=True, color=BG, align=PP_ALIGN.CENTER)
    # question
    txt(s, question, Inches(.85), Inches(.1), Inches(11), Inches(.52),
        size=13, bold=True, color=GOLD)
    # divider
    rect(s, Inches(.12), Inches(.72), Inches(12.9), Inches(.025), DGRAY)

    # layout: text left, images right (or full width if no images)
    has_imgs = bool(images)
    text_w = Inches(5.8) if has_imgs else Inches(12.7)

    # Build multiline text
    lines = []
    for a in answers:
        if isinstance(a, tuple):
            lines.append(a[0] + "  " + a[1])
        else:
            lines.append(a)
    full = "\n".join(lines)
    txt(s, full, Inches(.18), Inches(.82), text_w, Inches(6.3),
        size=12.5, color=WHITE, wrap=True)

    # Images
    if has_imgs:
        n = len(images)
        if n == 1:
            f = images[0] if isinstance(images[0], str) else images[0][0]
            img(s, f, Inches(6.2), Inches(.8), Inches(6.8), Inches(6.3))
        elif n == 2:
            for i, item in enumerate(images):
                f = item if isinstance(item, str) else item[0]
                x = Inches(6.2) + i * Inches(3.5)
                img(s, f, x, Inches(.8), Inches(3.3), Inches(6.3))
        elif n == 3:
            for i, item in enumerate(images):
                f = item if isinstance(item, str) else item[0]
                x = Inches(6.2) + i * Inches(2.35)
                img(s, f, x, Inches(.8), Inches(2.2), Inches(6.3))
        elif n >= 4:
            positions = [
                (Inches(6.2), Inches(.8)),
                (Inches(9.7), Inches(.8)),
                (Inches(6.2), Inches(3.9)),
                (Inches(9.7), Inches(3.9)),
            ]
            for i, item in enumerate(images[:4]):
                f = item if isinstance(item, str) else item[0]
                img(s, f, positions[i][0], positions[i][1], Inches(3.3), Inches(2.9))

    return s

